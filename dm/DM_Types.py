    locations: dict
    current_location_key: str | None
    legal_records: dict
    pending_reports: list
    pending_arrest: dict | None
    known_locations: set
    _last_scene_roster: tuple | None
    _pending_population: list
    _population_in_flight: int
    _population_done: Any

