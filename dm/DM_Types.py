    def _unique_entity_key(self, base_name) -> str: ...
    def _get_target_name(self, include_background=False, include_objects=True) -> str | None: ...
    def _is_party_member(self, entity_name) -> bool: ...
    def _is_background(self, entity_name) -> bool: ...
    def load_rules(self, rules_dir) -> None: ...
    def _resolve_player_name(self, template=None) -> str: ...
    def _rename_player_entity(self, new_name) -> bool: ...
    def load_scenario_definition(self, scenario_name) -> None: ...
    def load_scenario(self, skip_llm_generation=False) -> None: ...
    def enter_room(self, room_key, arrival_band=1, skip_llm_generation=False) -> bool: ...
    def _instance_entities(self, entity_entries, party_pool=None, skip_llm_generation=False) -> list: ...
    def _current_room(self) -> dict | None: ...
