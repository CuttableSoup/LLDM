    def _tick_conversation_partner(self) -> None: ...
    def _population_prompt_settings(self) -> dict: ...
    def _population_settings(self) -> dict: ...
    def _current_polity_language(self) -> str | None: ...
    def _resolve_region_polity(self, x, y) -> str | None: ...
    def _find_polity(self, name) -> dict | None: ...
    def format_currency(self, amount) -> str: ...
    def current_polity(self) -> str | None: ...
    def report_crime(self, crime, offender, victim=None, subject=None) -> list: ...
