    def move_toward_or_away(self, entity_name, opponent_name, direction) -> dict | None: ...
    def _apply_party_formation(self) -> None: ...
    def _apply_pending_population(self) -> None: ...
    def _apply_npc_generation(self, instance_name, party_pool, instance_names_so_far, skip_llm_generation) -> None: ...
